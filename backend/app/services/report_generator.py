"""Comprehensive Pentest Report Generator producing professional Markdown and HTML reports."""

from __future__ import annotations

import os
import json
import pathlib
from datetime import datetime, timezone
from typing import Dict, Any, List, Optional
from backend.app.storage.findings_db import findings_db
from backend.app.services.verification_planner import verification_planner


class ReportGenerator:
    def __init__(self, root_dir: Optional[pathlib.Path] = None):
        self.root_dir = root_dir or pathlib.Path(__file__).resolve().parent.parent.parent.parent
        self.reports_dir = self.root_dir / "toolkit" / "10-reports"
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate_report(self, target_id: str, campaign_name: str = "Automated Lab Assessment") -> Dict[str, Any]:
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        clean_target = target_id.replace(":", "-").replace("/", "-")
        findings = findings_db.list_findings(target_id=target_id)
        summary = findings_db.get_summary(target_id=target_id)

        # 1. Generate Markdown Report
        md_content = self._render_markdown(target_id, campaign_name, ts, findings, summary)
        md_path = self.reports_dir / f"{clean_target}_report.md"
        md_path.write_text(md_content, encoding="utf-8")

        # 2. Generate HTML Report
        html_content = self._render_html(target_id, campaign_name, ts, findings, summary, md_content)
        html_path = self.reports_dir / f"{clean_target}_report.html"
        html_path.write_text(html_content, encoding="utf-8")

        return {
            "target_id": target_id,
            "campaign_name": campaign_name,
            "generated_at": ts,
            "findings_count": len(findings),
            "summary": summary,
            "markdown_path": str(md_path.relative_to(self.root_dir)).replace("\\", "/"),
            "html_path": str(html_path.relative_to(self.root_dir)).replace("\\", "/"),
            "markdown_content": md_content,
        }

    def get_report(self, target_id: str) -> Optional[Dict[str, Any]]:
        clean_target = target_id.replace(":", "-").replace("/", "-")
        md_path = self.reports_dir / f"{clean_target}_report.md"
        if not md_path.exists():
            return None
        return {
            "target_id": target_id,
            "markdown_content": md_path.read_text(encoding="utf-8"),
            "markdown_path": str(md_path.relative_to(self.root_dir)).replace("\\", "/"),
        }

    def list_reports(self) -> List[Dict[str, Any]]:
        reports = []
        for p in self.reports_dir.glob("*_report.md"):
            name = p.stem.replace("_report", "")
            reports.append({
                "target_id": name,
                "file_name": p.name,
                "path": str(p.relative_to(self.root_dir)).replace("\\", "/"),
                "modified_at": datetime.fromtimestamp(p.stat().st_mtime, timezone.utc).isoformat(),
            })
        return sorted(reports, key=lambda x: x["modified_at"], reverse=True)

    def _render_markdown(
        self,
        target_id: str,
        campaign: str,
        ts: str,
        findings: list,
        summary: dict,
    ) -> str:
        by_sev = summary.get("by_severity", {})
        
        lines = [
            f"# SECURITY ASSESSMENT REPORT",
            f"**Target**: `{target_id}` | **Campaign**: {campaign} | **Date**: {ts}",
            f"**Generated By**: AI-Pentest Copilot v5.0 (Strict Read-Only Verification Engine)",
            "",
            "---",
            "",
            "## 1. EXECUTIVE SUMMARY",
            f"During the security assessment of target **`{target_id}`**, automated reconnaissance and vulnerability correlation identified **{len(findings)}** actionable findings.",
            "",
            "### Risk Breakdown",
            f"- **Critical**: `{by_sev.get('CRITICAL', 0)}`",
            f"- **High**: `{by_sev.get('HIGH', 0)}`",
            f"- **Medium**: `{by_sev.get('MEDIUM', 0)}`",
            f"- **Low**: `{by_sev.get('LOW', 0)}`",
            f"- **Informational**: `{by_sev.get('INFO', 0)}`",
            "",
            "### Methodology & Authorization",
            "- **Scope Enforcement**: Target validated against authorized scopes (RFC 1918 Private Address / Localhost).",
            "- **Zero Exploitation Principle**: No destructive exploitation payloads were executed. All findings are substantiated by passive banner analysis, tool signatures, and non-destructive verification plans.",
            "",
            "---",
            "",
            "## 2. DETAILED FINDINGS PROFILES",
        ]

        if not findings:
            lines.append("No vulnerabilities identified for this target.")
        else:
            for idx, f in enumerate(findings, 1):
                plan = verification_planner.generate_plan(f)
                lines.extend([
                    f"### [{idx}] {f.title}",
                    f"- **Finding ID**: `{f.id}`",
                    f"- **Severity**: `{f.cvss_severity.value}` (CVSS v3: `{f.cvss_score:.1f}`)",
                    f"- **Status**: `{f.status.value}`",
                    f"- **CVE Reference**: `{f.cve_id or 'N/A'}` | **CWE**: `{f.cwe_id or 'N/A'}`",
                    f"- **Affected Asset**: `{f.affected_asset}`",
                    "",
                    "#### Description",
                    f"{f.description}",
                    "",
                    "#### Immutable Evidence Chain",
                ])
                for ev in f.evidence_chain:
                    lines.append(f"- **Tool**: `{ev.tool}` | **File**: `{ev.file_path}`")
                    lines.append("  ```text\n  " + ev.matched_text + "\n  ```")

                lines.extend([
                    "#### Safe Read-Only Verification Plan",
                ])
                for s in plan.steps:
                    lines.append(f"{s.step_number}. **{s.name}**")
                    lines.append("   ```bash\n   " + s.command + "\n   ```")
                    lines.append(f"   - *Expected*: {s.expected_evidence}")

                if f.remediation:
                    lines.extend([
                        "",
                        "#### Remediation Guidance",
                        f"{f.remediation}",
                    ])
                lines.append("\n---\n")

        lines.extend([
            "## 3. REMEDIATION ROADMAP",
            "1. **Immediate Action (Within 24 Hours)**:",
            "   - Patch or upgrade services with Critical/High CVSS ratings (e.g. upgrade vulnerable web servers).",
            "   - Restrict access to open administrative ports via firewall ingress rules.",
            "2. **Short-Term Action (Within 7 Days)**:",
            "   - Implement security headers and disable version banner disclosure (ServerTokens Prod).",
            "   - Re-run verification checks to validate remediation effectiveness.",
            "3. **Long-Term Action**:",
            "   - Integrate automated continuous reconnaissance in CI/CD pipeline.",
            "",
            "---",
            "*Report generated automatically by AI-Pentest Copilot. Evidence logs preserved in immutable audit repository.*",
        ])

        return "\n".join(lines)

    def _render_html(
        self,
        target_id: str,
        campaign: str,
        ts: str,
        findings: list,
        summary: dict,
        md_content: str,
    ) -> str:
        by_sev = summary.get("by_severity", {})
        crit_count = by_sev.get('CRITICAL', 0)
        high_count = by_sev.get('HIGH', 0)
        med_count = by_sev.get('MEDIUM', 0)
        low_count = by_sev.get('LOW', 0)

        finding_cards = []
        for f in findings:
            score_str = f"{f.cvss_score:.1f}"
            sev_class = f.cvss_severity.value.lower()
            cve_txt = f.cve_id or "None"
            rem_txt = f.remediation or "Review system configuration."
            card = f"""
    <div style="background: #182234; border: 1px solid #334155; border-radius: 8px; padding: 16px; margin-bottom: 16px;">
      <div style="display:flex; justify-content:space-between; align-items:center;">
        <h3 style="margin:0; color:#38bdf8;">{f.title}</h3>
        <span class="badge {sev_class}">{f.cvss_severity.value} (CVSS {score_str})</span>
      </div>
      <p style="font-size:13px; color:#94a3b8; margin: 8px 0;">Asset: <code>{f.affected_asset}</code> | Status: <strong>{f.status.value}</strong> | CVE: <code>{cve_txt}</code></p>
      <p>{f.description}</p>
      <h4>Remediation</h4>
      <p style="color:#86efac;">{rem_txt}</p>
    </div>
            """
            finding_cards.append(card)

        cards_html = "".join(finding_cards)

        return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Security Assessment Report - {target_id}</title>
  <style>
    body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background: #0f172a; color: #e2e8f0; line-height: 1.6; padding: 40px; margin: 0; }}
    .container {{ max-width: 900px; margin: 0 auto; background: #1e293b; padding: 40px; border-radius: 12px; border: 1px solid #334155; }}
    h1 {{ color: #38bdf8; border-bottom: 2px solid #334155; padding-bottom: 12px; margin-top: 0; }}
    h2 {{ color: #7dd3fc; border-bottom: 1px solid #334155; padding-bottom: 8px; margin-top: 32px; }}
    h3 {{ color: #f8fafc; margin-top: 24px; }}
    .badge {{ display: inline-block; padding: 4px 8px; border-radius: 4px; font-weight: bold; font-size: 12px; }}
    .crit {{ background: #7f1d1d; color: #fca5a5; }}
    .high {{ background: #7c2d12; color: #fdba74; }}
    .med {{ background: #78350f; color: #fde047; }}
    .low {{ background: #1e3a8a; color: #93c5fd; }}
    .stat-box {{ display: flex; gap: 12px; margin: 20px 0; }}
    .stat-item {{ flex: 1; padding: 12px; border-radius: 8px; text-align: center; border: 1px solid #334155; }}
    pre {{ background: #090d16; padding: 12px; border-radius: 6px; overflow-x: auto; color: #a5f3fc; font-family: monospace; }}
    code {{ background: #090d16; padding: 2px 6px; border-radius: 4px; color: #38bdf8; font-family: monospace; }}
    .footer {{ margin-top: 40px; padding-top: 20px; border-top: 1px solid #334155; font-size: 12px; color: #64748b; text-align: center; }}
  </style>
</head>
<body>
  <div class="container">
    <h1>Security Assessment Report</h1>
    <p><strong>Target:</strong> <code>{target_id}</code> | <strong>Campaign:</strong> {campaign} | <strong>Generated:</strong> {ts}</p>
    
    <div class="stat-box">
      <div class="stat-item crit"><span style="font-size:24px; font-weight:bold;">{crit_count}</span><br>Critical</div>
      <div class="stat-item high"><span style="font-size:24px; font-weight:bold;">{high_count}</span><br>High</div>
      <div class="stat-item med"><span style="font-size:24px; font-weight:bold;">{med_count}</span><br>Medium</div>
      <div class="stat-item low"><span style="font-size:24px; font-weight:bold;">{low_count}</span><br>Low</div>
    </div>

    <h2>Executive Summary</h2>
    <p>This report compiles findings from multi-tool reconnaissance and vulnerability correlation adhering strictly to read-only security validation standards.</p>

    <h2>Total Findings: {len(findings)}</h2>
    {cards_html}

    <div class="footer">
      AI-Pentest Copilot v5.0 - Confidential Security Assessment Documentation
    </div>
  </div>
</body>
</html>
"""


report_generator = ReportGenerator()
