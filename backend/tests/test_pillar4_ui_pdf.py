def test_topology_attack_paths_for_ui_walkthrough(client):
    """Verify GET /api/topology/{target_id} provides structured attack paths for the Walkthrough Player."""
    test_target = "192.168.100.153"
    res = client.get(f"/api/topology/{test_target}")
    assert res.status_code == 200
    data = res.json()

    assert "nodes" in data
    assert "edges" in data
    assert "attack_paths" in data

    # Topology must include attack paths with required fields for walkthrough player
    if len(data["attack_paths"]) > 0:
        first_path = data["attack_paths"][0]
        assert "id" in first_path
        assert "title" in first_path
        assert "steps" in first_path
        assert "severity" in first_path
        assert "node_ids" in first_path

        # Each step contains phase, node_id, and description for highlighting and navigation
        if len(first_path["steps"]) > 0:
            first_step = first_path["steps"][0]
            assert "phase" in first_step
            assert "node_id" in first_step
            assert "description" in first_step


def test_walkthrough_hitl_action_proposal(client):
    """Verify 1-Click HITL Action Proposal triggered from the attack path walkthrough drawer."""
    test_target = "192.168.100.153"
    probe_payload = {
        "target_id": test_target,
        "name": "Verify attack step probe",
        "command": f"nmap -sV -sC -p 80,443 {test_target}",
        "description": "Walkthrough UI: Verify attack entrypoint on web ports safely before exploitation.",
        "expected_evidence": "HTTP Response / Service banner match",
    }

    res = client.post("/api/action/propose", json=probe_payload)
    assert res.status_code == 200
    data = res.json()

    assert "action_id" in data
    assert data["status"] == "PROPOSED"

    # Verify action appears in pending actions queue
    r_list = client.get(f"/api/action/pending?target_id={test_target}")
    assert r_list.status_code == 200
    pending_data = r_list.json()
    assert pending_data["count"] >= 1
    assert any(a["action_id"] == data["action_id"] for a in pending_data["actions"])
