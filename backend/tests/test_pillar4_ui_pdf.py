def test_report_generator_pdf_integration():
    """Verify that report_generator.generate_report automatically creates a .pdf file."""
    test_target = "test-target-pillar4-auto"
    f_id = "FIND-AUTO-P4-TEST"

    findings_db.create_finding(
        f_id,
        FindingCreate(
            target_id=test_target,
            title="Exposed Database Management Interface",
            cve_id="CVE-2023-9999",
            cwe_id="CWE-284",
            cvss_score=8.5,
            cvss_severity=FindingSeverity.HIGH,
            status=FindingStatus.VERIFIED,
            affected_asset=f"{test_target}:5432",
            description="PostgreSQL port open without network ACL restriction.",
            remediation="Bind PostgreSQL to localhost or private VPC subnet.",
            evidence_chain=[],
            trustworthy=True,
            is_simulated=False,
        ),
    )

    try:
        rep = report_generator.generate_report(test_target)
        assert rep is not None
        assert "pdf_path" in rep
        assert rep["pdf_path"].endswith(".pdf")

        # Check physical file existence
        root_dir = report_generator.root_dir
        disk_pdf = root_dir / rep["pdf_path"]
        assert disk_pdf.exists()
        assert disk_pdf.stat().st_size > 1000

        # Verify get_report includes pdf_path
        cached_rep = report_generator.get_report(test_target)
        assert cached_rep is not None
        assert "pdf_path" in cached_rep
        assert cached_rep["pdf_path"] == rep["pdf_path"]
    finally:
        findings_db.delete_finding(f_id)


def test_api_get_pdf_report_endpoints(client):
    """Verify REST API GET /api/reports/{target_id}/pdf for inline view and download attachment."""
    test_target = "192.168.100.153"
    # Ensure a report exists first
    report_generator.generate_report(test_target)

    # 1. Test inline preview mode (default)
    res_inline = client.get(f"/api/reports/{test_target}/pdf")
    assert res_inline.status_code == 200
    assert res_inline.headers["content-type"] == "application/pdf"
    assert "inline;" in res_inline.headers.get("content-disposition", "")
    assert f'{test_target}_report.pdf' in res_inline.headers.get("content-disposition", "")
    assert res_inline.content.startswith(b"%PDF-1.4")

    # 2. Test download attachment mode
    res_attach = client.get(f"/api/reports/{test_target}/pdf?download=true")
    assert res_attach.status_code == 200
    assert res_attach.headers["content-type"] == "application/pdf"
    assert "attachment;" in res_attach.headers.get("content-disposition", "")
    assert f'{test_target}_report.pdf' in res_attach.headers.get("content-disposition", "")
    assert len(res_attach.content) > 2000


