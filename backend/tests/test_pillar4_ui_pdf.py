def test_pdf_canvas_primitives():
    """Test low-level PDF 1.4 vector primitives generated by pure-Python PDFCanvas."""
    canvas = PDFCanvas()

    # Test vector shapes and styling
    canvas.draw_rect(50, 750, 495, 40, fill_color=(0.1, 0.2, 0.4), stroke_color=(0.3, 0.5, 0.8), stroke_width=1.5)
    canvas.draw_line(50, 740, 545, 740, stroke_color=(0.8, 0.8, 0.8), stroke_width=1.0)
    canvas.draw_text(60, 765, "AI-Pentest Copilot Specimen Canvas", font="/F2", size=14, color=(1, 1, 1))

    # Test text escaping with parens, backslashes, and non-ascii
    escaped = sanitize_text("Target (Test \\ & Spec) - 100% Secure \u2014 Pure Python")
    assert "\\(" in escaped
    assert "\\)" in escaped
    assert "\\\\" in escaped

    # Multi-page transition
    canvas.new_page()
    canvas.draw_text(50, 800, "Page 2 Appendices", font="/F2", size=16, color=(0.1, 0.1, 0.1))

    pdf_bytes = canvas.finish()
    assert isinstance(pdf_bytes, bytes)
    assert pdf_bytes.startswith(b"%PDF-1.4\n")
    assert pdf_bytes.endswith(b"%%EOF\n")
    assert b"/Count 2" in pdf_bytes  # 2 pages
    assert b"xref" in pdf_bytes
    assert b"trailer" in pdf_bytes


